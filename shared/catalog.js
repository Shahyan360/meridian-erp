const text = (key, label, extra = {}) => ({
  key,
  label,
  type: "text",
  required: true,
  ...extra,
});
const number = (key, label, extra = {}) =>
  text(key, label, { type: "number", min: 0, ...extra });
const select = (key, label, options, extra = {}) =>
  text(key, label, { type: "select", options, ...extra });
const relation = (key, label, resource, extra = {}) =>
  text(key, label, { type: "relation", resource, ...extra });
const optional = (key, label, extra = {}) =>
  text(key, label, { required: false, ...extra });
const date = (key, label, extra = {}) =>
  text(key, label, { type: "date", ...extra });
